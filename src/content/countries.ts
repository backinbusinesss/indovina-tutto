import type { Difficulty } from '@/engine/types'

export type Region = 'europa' | 'asia' | 'africa' | 'nord-america' | 'centro-america-caraibi' | 'sud-america' | 'oceania'
export type Continent = 'Europa' | 'Asia' | 'Africa' | 'America' | 'Oceania'

export interface Country {
  iso2: string
  /** codice numerico ISO 3166-1, come in world-atlas */
  num: string
  name: string
  capital: string
  /** false quando la capitale è contesa o non ufficiale */
  capitalQuiz: boolean
  region: Region
  continent: Continent
  transcontinental: boolean
  currency: string
  /** solo quando c'è una lingua principale chiara */
  language: string | null
  /** 1 = lo conoscono tutti, 3 = poco noto */
  fame: Difficulty
  /** sagoma riconoscibile */
  shape: boolean
}

const CONTINENT: Record<Region, Continent> = {
  europa: 'Europa',
  asia: 'Asia',
  africa: 'Africa',
  'nord-america': 'America',
  'centro-america-caraibi': 'America',
  'sud-america': 'America',
  oceania: 'Oceania',
}

type Flag = 'noShape' | 'noCapitalQuiz' | 'trans'
type Row = [
  iso2: string,
  num: string,
  name: string,
  capital: string,
  currency: string,
  language: string | null,
  fame: Difficulty,
  flags?: Flag[],
  continent?: Continent,
]

function rows(region: Region, list: Row[]): Country[] {
  return list.map(([iso2, num, name, capital, currency, language, fame, flags = [], continent]) => ({
    iso2,
    num,
    name,
    capital,
    capitalQuiz: !flags.includes('noCapitalQuiz'),
    region,
    continent: continent ?? CONTINENT[region],
    transcontinental: flags.includes('trans'),
    currency,
    language,
    fame,
    shape: !flags.includes('noShape'),
  }))
}

