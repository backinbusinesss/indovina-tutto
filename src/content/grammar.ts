/** "dell'Italia", "della Francia", "del Perù", "degli Stati Uniti"… */
export function ofCountry(c: Pick<Country, 'name'>): string {
  const special = OF[c.name]
  if (special) return special
  if (/^[AEIOUÀÈÉÌÒÙ]/i.test(c.name)) return `dell'${c.name}`
  if (/[aà]$/.test(c.name)) return `della ${c.name}`
  return `del ${c.name}`
}
